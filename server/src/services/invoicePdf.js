import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const PAGE_WIDTH = 612;
const PAGE_HEIGHT = 792;
const MARGIN = 48;
const FOOTER = 'Generated by NovaPay. Sandbox demo, not a tax document.';

export function formatInvoiceMinor(minor, currency) {
  const code = String(currency || '').toUpperCase();
  let exponent = 2;
  try { exponent = new Intl.NumberFormat('en', { style: 'currency', currency: code }).resolvedOptions().maximumFractionDigits; }
  catch { throw new TypeError('Invoice currency is invalid.'); }
  const amount = Number(minor);
  if (!Number.isSafeInteger(amount)) throw new TypeError('Invoice amount is invalid.');
  const major = amount / (10 ** exponent);
  return `${code} ${new Intl.NumberFormat('en-US', { minimumFractionDigits: exponent, maximumFractionDigits: exponent }).format(major)}`;
}

function pdfText(value) {
  return String(value ?? '').normalize('NFKD').replace(/[^\x20-\x7E]/g, '?').replace(/[\r\n\t]+/g, ' ').trim();
}

function wrap(text, font, size, width) {
  const words = pdfText(text).split(/\s+/).filter(Boolean);
  const lines = [];
  let current = '';
  for (const word of words) {
    if (font.widthOfTextAtSize(word, size) <= width) {
      const next = current ? `${current} ${word}` : word;
      if (font.widthOfTextAtSize(next, size) <= width) current = next;
      else { if (current) lines.push(current); current = word; }
    } else {
      if (current) lines.push(current);
      current = '';
      let part = '';
      for (const character of word) {
        const next = part + character;
        if (font.widthOfTextAtSize(next, size) > width && part) { lines.push(part); part = character; }
        else part = next;
      }
      current = part;
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

export async function createInvoicePdf(invoice) {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const pages = [];
  let page;
  let y;
  const color = rgb(0.1, 0.16, 0.24);
  const muted = rgb(0.36, 0.42, 0.5);

  function addPage() {
    page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
    pages.push(page);
    y = PAGE_HEIGHT - MARGIN;
    page.drawText('NovaPay', { x: MARGIN, y, font: bold, size: 20, color });
    page.drawText(`Invoice ${pdfText(invoice.invoiceNumber)}`, { x: MARGIN, y: y - 26, font: bold, size: 14, color });
    const status = invoice.state === 'paid' ? 'Paid' : invoice.state === 'sent' ? 'Sent - SIMULATED, not delivered' : invoice.state === 'void' ? 'Void' : String(invoice.state || 'draft').toUpperCase();
    page.drawText(`Status: ${pdfText(status)}`, { x: MARGIN, y: y - 44, font, size: 10, color: muted });
    if (invoice.state === 'draft' || invoice.state === 'reviewed') page.drawText('DRAFT', { x: PAGE_WIDTH - 106, y: y - 3, font: bold, size: 16, color: rgb(0.75, 0.25, 0.12) });
    page.drawText(`Issue date: ${pdfText(invoice.issueDate || '')}    Due date: ${pdfText(invoice.dueDate || '')}`, { x: MARGIN, y: y - 62, font, size: 10, color: muted });
    y -= 86;
    page.drawText('BILL TO', { x: MARGIN, y, font: bold, size: 9, color: muted });
    y -= 14;
    for (const line of [...wrap(invoice.customerName, font, 11, 260), ...wrap(invoice.customerEmail, font, 10, 260)]) {
      page.drawText(line, { x: MARGIN, y, font, size: line === pdfText(invoice.customerName) ? 11 : 10, color }); y -= 14;
    }
    y -= 16;
    page.drawText('Description', { x: MARGIN, y, font: bold, size: 9, color: muted });
    page.drawText('Qty', { x: 352, y, font: bold, size: 9, color: muted });
    page.drawText('Unit price', { x: 395, y, font: bold, size: 9, color: muted });
    page.drawText('Line total', { x: 500, y, font: bold, size: 9, color: muted });
    y -= 10;
    page.drawLine({ start: { x: MARGIN, y }, end: { x: PAGE_WIDTH - MARGIN, y }, thickness: 0.6, color: muted });
    y -= 18;
  }

  function ensureSpace(height) { if (y - height < 74) addPage(); }
  function drawWrapped(text, x, width, size = 10, lineHeight = 13, useBold = false) {
    const lines = wrap(text, useBold ? bold : font, size, width);
    for (const line of lines) {
      ensureSpace(lineHeight);
      page.drawText(line, { x, y, font: useBold ? bold : font, size, color });
      y -= lineHeight;
    }
    return lines.length;
  }

  addPage();
  for (const item of invoice.lines || []) {
    const descriptionLines = wrap(item.description, font, 9, 270);
    const rowHeight = Math.max(18, descriptionLines.length * 12);
    ensureSpace(rowHeight + 4);
    descriptionLines.forEach((line, index) => page.drawText(line, { x: MARGIN, y: y - index * 12, font, size: 9, color }));
    page.drawText(pdfText(item.quantity), { x: 352, y, font, size: 9, color });
    page.drawText(formatInvoiceMinor(item.unitPriceMinor, invoice.currency), { x: 395, y, font, size: 9, color });
    page.drawText(formatInvoiceMinor(item.totalMinor, invoice.currency), { x: 500, y, font, size: 9, color });
    y -= rowHeight + 5;
  }

  ensureSpace(88);
  y -= 8;
  for (const [label, value, isTotal] of [
    ['Subtotal', invoice.subtotalMinor, false], ['Tax', invoice.taxMinor, false], ['Total', invoice.totalMinor, true],
  ]) {
    const activeFont = isTotal ? bold : font;
    page.drawText(label, { x: 390, y, font: activeFont, size: isTotal ? 12 : 10, color });
    page.drawText(formatInvoiceMinor(value, invoice.currency), { x: 475, y, font: activeFont, size: isTotal ? 12 : 10, color });
    y -= isTotal ? 21 : 16;
  }
  if (invoice.notes) {
    y -= 6;
    drawWrapped('Notes', MARGIN, PAGE_WIDTH - 2 * MARGIN, 10, 14, true);
    drawWrapped(invoice.notes, MARGIN, PAGE_WIDTH - 2 * MARGIN, 9, 12);
  }
  for (const currentPage of pages) currentPage.drawText(FOOTER, { x: MARGIN, y: 30, font, size: 8, color: muted });
  return Buffer.from(await pdf.save());
}
